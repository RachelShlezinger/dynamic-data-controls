using System.Text.Json;

namespace DynamicDataControls.Api.Models.DTOs;

/// <summary>
/// DTOs exchanged with the Python FastAPI AI service.
/// All serialization uses camelCase naming policy (via <c>JsonSerializerOptionsFactory</c>)
/// so C# PascalCase properties map correctly to Python's camelCase JSON keys.
/// Requirements: 7.2, 7.7
/// </summary>

// ── Request DTOs ──────────────────────────────────────────────────────────────

/// <summary>Metadata about a single business field sent as AI context.</summary>
/// <param name="Name">Friendly field name (e.g. "גיל").</param>
/// <param name="DataType">One of: Number, String, Date, Boolean.</param>
/// <param name="Description">Optional description of the field.</param>
public record AiFieldDto(string Name, string DataType, string? Description);

/// <summary>Metadata about a business entity with its fields, sent as AI context.</summary>
/// <param name="Name">Friendly entity name (e.g. "עובד").</param>
/// <param name="Fields">All fields that belong to this entity.</param>
public record AiEntityDto(string Name, IReadOnlyList<AiFieldDto> Fields);

/// <summary>Context payload containing all known entities and fields.</summary>
/// <param name="Entities">All available business entities with their fields.</param>
public record AiContextDto(IReadOnlyList<AiEntityDto> Entities);

/// <summary>
/// Full request body sent to <c>POST /parse</c> on the Python AI service.
/// </summary>
/// <param name="Description">Free-text description from the user (10–1,000 chars).</param>
/// <param name="Context">Schema context so the AI can resolve entity/field names.</param>
public record AiParseRequestDto(string Description, AiContextDto Context);

// ── Response DTOs ─────────────────────────────────────────────────────────────

/// <summary>
/// A single condition item returned by the Python AI service.
/// Uses non-positional record syntax so missing JSON keys fall back to safe defaults
/// rather than causing deserialization failures.
/// </summary>
public record AiConditionDto
{
    /// <summary>Friendly field name from the AI response (e.g. "גיל").</summary>
    public string FieldName { get; init; } = string.Empty;

    /// <summary>
    /// Operator string from the AI response (e.g. "LessThan").
    /// Must parse to a valid <c>OperatorType</c> enum value.
    /// </summary>
    public string Operator { get; init; } = string.Empty;

    /// <summary>
    /// Raw comparison value from the AI response.
    /// <list type="bullet">
    ///   <item><c>null</c> (C#) — the JSON "value" key was absent entirely.</item>
    ///   <item><see cref="JsonElement"/> with <c>ValueKind = Null</c> — key was present with JSON <c>null</c>
    ///   (valid for <c>IsNull</c> / <c>IsNotNull</c> operators).</item>
    /// </list>
    /// </summary>
    public JsonElement? Value { get; init; }
}

/// <summary>
/// Full response body returned by the Python AI service's <c>POST /parse</c> endpoint.
/// Uses non-positional record syntax for safe deserialization when optional keys are absent.
/// </summary>
public record AiParseResponseDto
{
    /// <summary>Suggested control name generated by the AI (e.g. "עובדים קטינים עם שכר גבוה").</summary>
    public string ControlName { get; init; } = string.Empty;

    /// <summary>Friendly name of the primary entity the control targets (e.g. "עובד").</summary>
    public string PrimaryEntity { get; init; } = string.Empty;

    /// <summary>Ordered list of conditions that build the WHERE clause. Must have ≥ 1 item.</summary>
    public IReadOnlyList<AiConditionDto> Conditions { get; init; } = Array.Empty<AiConditionDto>();
}
